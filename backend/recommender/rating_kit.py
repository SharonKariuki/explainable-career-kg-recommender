"""Volunteer rating of explanations: the human part of the Explainability Quality Score.

`sheet` writes the ten explanations every volunteer rates, generated by the
current engine for the ten everyday-language profiles of the explanation
sample (alternately each profile's first and second recommendation, so strong,
weaker and uncertain matches all appear). `summarise` reads the filled-in
ratings and reports each question (docs/explainability_rubric.md, section 5).

    python -m recommender.rating_kit sheet --run NAME                 # rating_sheet.csv and rating_sheet.md
    python -m recommender.rating_kit summarise --run NAME FILE.csv    # rating_summary.csv from the volunteers' answers

The ratings file has one row per rater and item: rater, item, H1, H2, H3, H4
(1-5) and H5 (free text). docs/volunteer_rating_kit.md gives the procedure.
"""

import argparse
import sys

import pandas as pd

from recommender.engine import DEFAULT_PARAMS, get_engine
from recommender.evaluation import describe_sets
from recommender.explanation import ExplanationGenerator, fit_level
from recommender.explanation_quality import HAND_WRITTEN_PROFILES
from recommender.results import configuration, run_dir, run_started, write_csv, write_manifest

QUESTIONS = {
    'H1': 'I understand why this career was recommended.',
    'H2': 'The explanation mentions the things that matter for this recommendation.',
    'H3': 'The explanation is easy to read.',
    'H4': 'After reading it, I trust this recommendation more.',
}
SCALE = '1 = strongly disagree, 2 = disagree, 3 = neither, 4 = agree, 5 = strongly agree'


def sheet_rows():
    engine, generator = get_engine(), ExplanationGenerator()
    rows = []
    for i, skills in enumerate(HAND_WRITTEN_PROFILES):
        rank = 1 if i % 2 == 0 else 2
        _, ranked = engine.rank(skills, top_k=rank)
        r = ranked[rank - 1]
        uncertain = any(c.low_confidence for c in r.skill_contributions)
        rows.append({'item': i + 1, 'skills': ', '.join(skills), 'rank': rank, 'career': r.title,
                     'fit': fit_level(r.score), 'uncertain_match': uncertain, 'explanation': generator.explain(r).text})
    return pd.DataFrame(rows)


def sheet_markdown(rows):
    lines = ['# AjiraGuide: rate ten explanations', '',
             'For each item, read the skills a student entered, the career AjiraGuide recommended and its explanation. '
             f'Then rate each statement from 1 to 5 ({SCALE}), and add any comment.', '']
    for r in rows.itertuples():
        lines += [f'## Item {r.item}', '', f'**Skills entered:** {r.skills}', '',
                  f'**Recommended career (#{r.rank}):** {r.career}', '', f'> {r.explanation}', '']
        lines += [f'- {key}. {text}  Rating: ___' for key, text in QUESTIONS.items()]
        lines += ['- H5. Anything confusing, missing or wrong? ______________________', '']
    return '\n'.join(lines)


def summarise(ratings):
    """Mean, spread and share agreeing (4 or 5) per question, overall and per item."""
    missing = {'rater', 'item', *QUESTIONS} - set(ratings.columns)
    if missing:
        raise ValueError(f'ratings file is missing columns: {", ".join(sorted(missing))}')
    long = ratings.melt(id_vars=['rater', 'item'], value_vars=list(QUESTIONS), var_name='question', value_name='rating')
    long = long.dropna(subset=['rating'])
    if not long.rating.between(1, 5).all():
        raise ValueError('every rating must be a whole number from 1 to 5')

    def stats(group):
        return pd.Series({'raters': group.rater.nunique(), 'mean': group.rating.mean(), 'sd': group.rating.std(),
                          'agree_share': (group.rating >= 4).mean()})
    overall = long.groupby('question').apply(stats, include_groups=False).assign(item='all').reset_index()
    per_item = long.groupby(['item', 'question']).apply(stats, include_groups=False).reset_index()
    return pd.concat([overall, per_item], ignore_index=True)[['item', 'question', 'raters', 'mean', 'sd', 'agree_share']].round(3)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('step', choices=['sheet', 'summarise'])
    parser.add_argument('--run', required=True)
    parser.add_argument('ratings', nargs='?', help='the filled-in ratings CSV (summarise only)')
    args = parser.parse_args(argv)
    if args.step == 'summarise' and not args.ratings:
        parser.error('summarise needs the ratings CSV')
    try:
        folder = run_dir(args.run)
    except (ValueError, FileExistsError) as error:
        parser.error(str(error))
    started = run_started(__spec__.name, sys.argv[1:] if argv is None else argv)

    if args.step == 'sheet':
        rows = sheet_rows()
        out = write_csv(rows, folder, 'rating_sheet.csv')
        (folder / 'rating_sheet.md').write_text(sheet_markdown(rows), encoding='utf-8')
        print(rows[['item', 'career', 'fit', 'uncertain_match']].to_string(index=False))
    else:
        table = summarise(pd.read_csv(args.ratings))
        out = write_csv(table, folder, 'rating_summary.csv')
        print(table[table.item == 'all'].to_string(index=False))
    write_manifest(folder, started, describe_sets({'explanation-sample': HAND_WRITTEN_PROFILES},
                                                  roles={'explanation-sample': 'development'}),
                   configuration(DEFAULT_PARAMS))
    print(f'\nWritten: {out}')


if __name__ == '__main__':
    main()
